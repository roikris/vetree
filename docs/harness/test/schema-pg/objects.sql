-- Sample objects for the 080 report test on the pinned Supabase Postgres image (schema-report-test.yml).
-- One of every covered kind; nothing here is ever applied to production.
CREATE TYPE public.mood AS ENUM ('sad', 'ok', 'happy');
CREATE DOMAIN public.pos AS integer NOT NULL DEFAULT 1 CHECK (VALUE > 0);
CREATE TYPE public.pair AS (a int, b text);
CREATE TABLE public.items (id bigserial PRIMARY KEY, name text NOT NULL DEFAULT 'x' COLLATE "C", m public.mood,
  n public.pos, g int GENERATED ALWAYS AS (length(name)) STORED, ident int GENERATED BY DEFAULT AS IDENTITY,
  UNIQUE (name) DEFERRABLE INITIALLY DEFERRED);
ALTER TABLE public.items ADD CONSTRAINT name_len CHECK (length(name) < 100) NOT VALID;
CREATE INDEX items_m ON public.items (m) WHERE m IS NOT NULL;
ALTER TABLE public.items ENABLE ROW LEVEL SECURITY;
CREATE POLICY "read" ON public.items FOR SELECT TO anon USING (true);
CREATE TABLE public.children (id int PRIMARY KEY, item_id bigint REFERENCES public.items(id) ON DELETE CASCADE);
REVOKE ALL ON public.items, public.children FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON public.items TO anon;
GRANT SELECT, INSERT ON public.items TO service_role WITH GRANT OPTION;
GRANT SELECT (item_id) ON public.children TO authenticated;
CREATE VIEW public.v_items WITH (security_invoker = true) AS SELECT id, name FROM public.items;
CREATE MATERIALIZED VIEW public.mv_items AS SELECT id FROM public.items;
CREATE FUNCTION public.touch() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $f$ BEGIN RETURN NEW; END $f$;
CREATE TRIGGER items_touch BEFORE UPDATE ON public.items FOR EACH ROW EXECUTE FUNCTION public.touch();
ALTER TABLE public.items DISABLE TRIGGER items_touch;
CREATE PROCEDURE public.noop() LANGUAGE sql AS $f$ SELECT 1 $f$;
-- production installs pg_trgm without a schema (so into public): its members must be excluded, not unsupported
CREATE EXTENSION IF NOT EXISTS pg_trgm SCHEMA public;
CREATE TABLE public.parted (id int, d date) PARTITION BY RANGE (d);
CREATE TABLE public.parted_2026 PARTITION OF public.parted FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE INDEX parted_d ON public.parted (d);
CREATE PUBLICATION pub1 FOR TABLE public.items (id, name) WHERE (id > 0) WITH (publish = 'insert');
